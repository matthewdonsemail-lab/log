// Rule 44: every browser log-cli drives has the same pieces, in the same places.
// Usage: bun scripts/checkBrowserParity.ts           (pre-commit and pre-push: refuses a missing piece)
//        bun scripts/checkBrowserParity.ts --write   (regenerates the table in docs/browsers.md)
//
// For each name in BROWSER_DRIVERS (src/browser/driver/types.ts):
//   src/browser/<name>/index.ts       exports <name>Capabilities (every capability) and <name>Driver
//   src/browser/<name>/<name>.test.ts its tests
//   python/browserDriver.py           the name in BROWSERS and an opener in OPENERS
//   docs/browsers.md                  its column, the table generated from the rows
// and no folder in src/browser/ other than a listed browser or a domain every browser shares (SHARED_DOMAINS).
// Not too strict: a capability may be `notBuilt`; those are listed on every commit, never refused.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BROWSER_CAPABILITIES, BROWSER_DRIVERS } from "../src/browser/driver/types.ts";
import type { BrowserCapabilities } from "../src/browser/driver/types.ts";

const root = join(import.meta.dir, "..");
/** The domains every browser shares, beside the browsers themselves (rule 57): the driver, each run's files and launch budget, the proxy, inspect and flows. */
const SHARED_DOMAINS = ["driver", "run", "proxy", "inspect", "flow"];
const problems: string[] = [];
const rows = new Map<string, BrowserCapabilities>();
const capabilities = Object.keys(BROWSER_CAPABILITIES) as (keyof typeof BROWSER_CAPABILITIES)[];

for (const name of BROWSER_DRIVERS) {
  const folder = join(root, "src/browser", name);
  if (!existsSync(join(folder, "index.ts"))) {
    problems.push(`src/browser/${name}/index.ts is missing: every browser is a domain of its own`);
    continue;
  }
  const mod = (await import(join(folder, "index.ts"))) as Record<string, unknown>;
  const row = mod[`${name}Capabilities`] as BrowserCapabilities | undefined;
  if (!row) problems.push(`src/browser/${name} doesn't export ${name}Capabilities (its row of the parity table)`);
  else {
    for (const c of capabilities) if (!row[c]) problems.push(`${name}Capabilities has no "${c}" (say built, notBuilt or notApplicable, and how)`);
    rows.set(name, row);
  }
  if (typeof mod[`${name}Driver`] !== "function") problems.push(`src/browser/${name} doesn't export ${name}Driver (its BrowserDriver)`);
  if (!existsSync(join(folder, `${name}.test.ts`))) problems.push(`src/browser/${name}/${name}.test.ts is missing`);
}

for (const entry of readdirSync(join(root, "src/browser"), { withFileTypes: true })) {
  if (entry.isDirectory() && !SHARED_DOMAINS.includes(entry.name) && !(BROWSER_DRIVERS as readonly string[]).includes(entry.name)) {
    problems.push(`src/browser/${entry.name} isn't in BROWSER_DRIVERS: add it there, add it to SHARED_DOMAINS when every browser uses it, or move it out of src/browser`);
  }
}

const python = readFileSync(join(root, "python/browserDriver.py"), "utf8");
const pyBrowsers = python.match(/^BROWSERS = \(([^)]*)\)/m)?.[1] ?? "";
const pyOpeners = python.match(/^OPENERS = \{([^}]*)\}/m)?.[1] ?? "";
for (const name of BROWSER_DRIVERS) {
  if (!pyBrowsers.includes(`"${name}"`)) problems.push(`python/browserDriver.py BROWSERS doesn't list "${name}"`);
  if (!pyOpeners.includes(`"${name}":`)) problems.push(`python/browserDriver.py OPENERS has no opener for "${name}"`);
}

const START = "<!-- browsers:start · generated by `bun run browsers:docs` from src/browser/<name>/types.ts. Not edited by hand. -->";
const END = "<!-- browsers:end -->";
const mark = { built: "built", notBuilt: "**not built**", notApplicable: "n/a" } as const;
const cell = (row: BrowserCapabilities | undefined, c: (typeof capabilities)[number]) => (row?.[c] ? `${mark[row[c].status]}: ${row[c].how.replace(/\|/g, "\\|")}` : "missing");
const table = [
  START,
  "",
  `| Capability | What it means | ${BROWSER_DRIVERS.join(" | ")} |`,
  `| --- | --- | ${BROWSER_DRIVERS.map(() => "---").join(" | ")} |`,
  ...capabilities.map((c) => `| \`${c}\` | ${BROWSER_CAPABILITIES[c]} | ${BROWSER_DRIVERS.map((n) => cell(rows.get(n), c)).join(" | ")} |`),
  "",
  END,
].join("\n");

const docsPath = join(root, "docs/browsers.md");
const docs = existsSync(docsPath) ? readFileSync(docsPath, "utf8").replace(/\r\n/g, "\n") : "";
const current = docs.includes(START) && docs.includes(END) ? docs.slice(docs.indexOf(START), docs.indexOf(END) + END.length) : null;
if (process.argv.includes("--write")) {
  if (!current) throw new Error("docs/browsers.md has no browsers:start/browsers:end markers");
  writeFileSync(docsPath, docs.replace(current, table));
  console.log("docs/browsers.md: parity table regenerated.");
} else if (current !== table) {
  problems.push("docs/browsers.md's parity table is out of date: bun run browsers:docs");
}

const notBuilt = [...rows].flatMap(([name, row]) => capabilities.filter((c) => row[c].status === "notBuilt").map((c) => `${name}.${c}`));
if (problems.length) {
  console.error(`check:browsers refused (rule 44):\n${problems.map((p) => `- ${p}`).join("\n")}`);
  process.exit(1);
}
console.log(`check:browsers OK: ${BROWSER_DRIVERS.join(", ")} each have their domain, row, driver, tests, Python opener and docs column.${notBuilt.length ? ` Not built yet: ${notBuilt.join(", ")}.` : ""}`);
