// Emits the generated Twenty GraphQL client into src/twenty/graphql/generated,
// the same way blaster (`pnpm twenty:client`, packages/core) and the dialer
// (`bun run api:client`, packages/shared → @dialer/shared/api) do: introspect
// the live workspace and let twenty-client-sdk write a typed genql client. The
// workspace is the schema, so socialAccounts, agencyListings and every field
// scripts/twentySetup.mjs added arrive with exact types.
//
// Differences from blaster's emitter, both for log-cli's conventions:
//   - relative specifiers end in .ts (log-cli runs from source with Bun);
//   - every file is stamped `@generated`, which the naming gate skips.
//
// Usage:
//   bun run twenty:client            regenerate from the live workspace
//   bun run twenty:client:check      fail when the committed client is stale
//   ... --schema path/to/schema.graphql   work offline from saved SDL
// TWENTY_BASE_URL / TWENTY_API_KEY come from the env or log-cli/.env.local.
import { existsSync, readFileSync } from 'node:fs'
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildClientSchema, getIntrospectionQuery, printSchema } from 'graphql'
import { generateCoreClientFromSchema } from 'twenty-client-sdk/generate'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const TARGET_DIR = join(root, 'src', 'twenty', 'graphql', 'generated')
const HEADER = `// @generated by \`bun run twenty:client\` (scripts/emitTwentyClient.mjs). Do not edit by hand.
// Source: introspection of the configured Twenty workspace. Regenerate whenever
// objects or fields change (scripts/twentySetup.mjs, or in Twenty itself).
// @ts-nocheck
`

function loadEnv() {
  const env = { ...process.env }
  const file = join(root, '.env.local')
  if (existsSync(file)) {
    for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
      const match = /^(TWENTY_BASE_URL|TWENTY_API_KEY)=(.*)$/.exec(line)
      if (match && !env[match[1]]) env[match[1]] = match[2].replace(/^"|"$/g, '')
    }
  }
  return env
}

const isSource = (name) => name.endsWith('.ts')

/** Relative imports point at .ts files: log-cli runs from source and never emits JS. */
const toTypeScriptSpecifiers = (content) => content.replace(/(from\s+['"]\.[^'"]*)\.js(['"])/g, '$1.ts$2')

const withoutOwnTsNocheck = (content) => content.replace(/^\/\/ @ts-nocheck\r?\n/, '')

async function collect(dir, base = dir) {
  const files = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) files.push(...(await collect(path, base)))
    else if (isSource(entry.name)) {
      const body = toTypeScriptSpecifiers(withoutOwnTsNocheck(await readFile(path, 'utf8')))
      files.push([relative(base, path).split('\\').join('/'), HEADER + body.replace(/\r\n/g, '\n')])
    }
  }
  return files.sort(([a], [b]) => a.localeCompare(b))
}

async function readSchema() {
  const flag = process.argv.indexOf('--schema')
  if (flag !== -1) return readFile(process.argv[flag + 1], 'utf8')
  const env = loadEnv()
  if (!env.TWENTY_BASE_URL || !env.TWENTY_API_KEY) {
    console.error('TWENTY_BASE_URL and TWENTY_API_KEY are required (log-cli/.env.local), or pass --schema <file>.')
    process.exit(1)
  }
  const url = `${env.TWENTY_BASE_URL.replace(/\/+$/, '').replace(/\/rest$/, '')}/graphql`
  const response = await fetch(url, {
    method: 'POST',
    headers: { Authorization: `Bearer ${env.TWENTY_API_KEY}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query: getIntrospectionQuery() })
  })
  if (!response.ok) {
    console.error(`Introspection failed: HTTP ${response.status} from ${url}.`)
    process.exit(1)
  }
  const body = await response.json()
  if (body.errors?.length || !body.data) {
    console.error(`Introspection errors: ${JSON.stringify(body.errors ?? 'empty response').slice(0, 500)}`)
    process.exit(1)
  }
  return printSchema(buildClientSchema(body.data))
}

const schema = await readSchema()
const scratch = await mkdtemp(join(tmpdir(), 'logCliTwentyClient'))
await generateCoreClientFromSchema({ schema, outputPath: scratch, clientWrapperTemplateSource: '' })
const emitted = await collect(scratch)
await rm(scratch, { recursive: true, force: true })

if (process.argv.includes('--check')) {
  let stale = false
  const names = emitted.map(([name]) => name)
  for (const [name, content] of emitted) {
    if ((await readFile(join(TARGET_DIR, name), 'utf8').catch(() => '')) !== content) {
      console.error(`${name} is stale: run \`bun run twenty:client\` and commit the result.`)
      stale = true
    }
  }
  const onDisk = existsSync(TARGET_DIR) ? (await collect(TARGET_DIR)).map(([name]) => name) : []
  for (const name of onDisk.filter((f) => !names.includes(f))) {
    console.error(`${name} is no longer emitted by the generator: delete it.`)
    stale = true
  }
  if (stale) process.exit(1)
  console.log(`Generated Twenty client is up to date (${names.length} files).`)
} else {
  await rm(TARGET_DIR, { recursive: true, force: true })
  for (const [name, content] of emitted) {
    const path = join(TARGET_DIR, name)
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, content)
  }
  console.log(`Wrote ${emitted.length} files to ${relative(root, TARGET_DIR)}`)
}
