/**
 * `log facebook lifecycle` — every account's place in its lifecycle (rule 35): its
 * status, the state the lifecycle machine puts it in, and what onboarding has
 * left. `log facebook lifecycle states [--write]` — the machine's own state tree, and
 * `docs/lifecycle.md` generated from it. Reads Twenty only: nothing opens.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { lifecycleMachine, standingOf, stepsLeft, whereNow } from "../../marketplace/lifecycle/index.ts";
import { findAccount, listFacebookAccounts } from "../../marketplace/socialAccount/index.ts";
import { parseArgs, refuseError } from "../runner/helpers/index.ts";
import type { Command } from "../runner/types.ts";
import { renderLifecycleTable, renderStateTree, standingLine } from "./helpers/index.ts";
import type { LifecycleRow } from "./helpers/index.ts";

export * from "./helpers/index.ts";

export const LIFECYCLE_USAGE = [
  "Usage: log facebook lifecycle [--account <name>] [--json]",
  "       log facebook lifecycle states [--write]   (the machine's state tree; --write regenerates docs/lifecycle.md)",
].join("\n");

const DOC_PATH = join(import.meta.dir, "..", "..", "..", "docs", "lifecycle.md");
const GENERATED = "<!-- generated by `log facebook lifecycle states --write`: edit src/marketplace/lifecycle/machine.ts, not this list -->";

export const lifecycleCommand: Command = {
  usage: LIFECYCLE_USAGE,
  platform: "facebook",
  name: "lifecycle",
  summary: "Each account's place in its lifecycle (rule 35): status, state, what onboarding has left; `states` prints the machine",
  args: "[states [--write]] [--account <name>] [--json]",
  async run(context, argv) {
    const parsed = parseArgs(argv, { boolean: ["json", "write"], valued: ["account"] });
    if (!parsed.ok) return { code: 1, stderr: `log facebook lifecycle: ${parsed.error}\n${LIFECYCLE_USAGE}` };
    const [sub] = parsed.positionals;

    if (sub === "states") {
      const tree = renderStateTree(lifecycleMachine.root as never).join("\n");
      if (!parsed.flags["write"]) return { code: 0, stdout: tree };
      const doc = (await Bun.file(DOC_PATH).exists()) ? await Bun.file(DOC_PATH).text() : "";
      const head = doc.includes(GENERATED) ? doc.slice(0, doc.indexOf(GENERATED)) : doc;
      writeFileSync(DOC_PATH, `${head.trimEnd()}\n\n${GENERATED}\n\n${tree}\n`);
      return { code: 0, stdout: `Wrote the state tree (${tree.split("\n").length} lines) to ${DOC_PATH}` };
    }
    if (sub !== undefined) return { code: 1, stderr: `log facebook lifecycle: unknown "${sub}"\n${LIFECYCLE_USAGE}` };

    try {
      const accounts = typeof parsed.flags["account"] === "string" ? [await findAccount(context.twenty, parsed.flags["account"])] : await listFacebookAccounts(context.twenty);
      const rows: (LifecycleRow & { standing: ReturnType<typeof standingOf> })[] = accounts.map((account) => {
        const standing = standingOf(account);
        return { accountName: account.accountName, status: account.status, state: whereNow(standing).state, stored: account.lifecycleState, left: stepsLeft(standing), standing };
      });
      if (parsed.flags["json"]) return { code: 0, stdout: JSON.stringify({ accounts: rows }, null, 2) };
      const lines = [renderLifecycleTable(rows)];
      if (rows.length === 1) lines.push(`  standing: ${standingLine(rows[0].standing)}`);
      return { code: 0, stdout: lines.join("\n") };
    } catch (error) {
      return refuseError("lifecycle", error);
    }
  },
};
