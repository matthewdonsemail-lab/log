export function faSvg(name: string, size: number = 16, color?: string): string {
  const definition = FA_ICONS[name];
  if (!definition) return "";
  const [width, height, , , path] = definition.icon;
  const d = Array.isArray(path) ? path.join(" ") : path;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${size}" height="${size}" aria-hidden="true" focusable="false"${color ? ` style="color:${color}"` : ""}><path fill="currentColor" d="${d}"/></svg>`;
}

